#!/usr/bin/env python3
"""Finalize and describe deterministic Santa Fe PMTiles shards."""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import sys
from pathlib import Path

ASSET_TARGET_BYTES = 24 * 1024 * 1024
ASSET_HARD_LIMIT_BYTES = 25 * 1024 * 1024
CITY_ID = "ar-santa-fe-capital"
LAYER_NAME = "santa_fe_buildings_3d"
OVERTURE_RELEASE = "2026-07-22.0"
OVERTURE_PY_VERSION = "1.0.1"
TIPPECANOE_COMMIT = "7c80fccdc17e4f8d9f4a52d518b4845290224366"
PMTILES_CLI_VERSION = "v1.30.1"


def canonical_json(value):
    return (json.dumps(value, sort_keys=True, separators=(",", ":"), ensure_ascii=False) + "\n").encode()


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--stats", required=True)
    parser.add_argument("--generated-ts", required=True)
    parser.add_argument("--pmtiles", required=True, nargs="+")
    args = parser.parse_args()

    source_sha = os.environ.get("SOURCE_SHA", "UNSET")
    stats = json.loads(Path(args.stats).read_text())
    finalized = []
    for value in args.pmtiles:
        path = Path(value)
        if not path.is_file():
            raise RuntimeError(f"PMTILES_MISSING:{path.name}")
        size = path.stat().st_size
        if size >= ASSET_HARD_LIMIT_BYTES:
            raise RuntimeError(f"PMTILES_EXCEEDS_CLOUDFLARE_HARD_LIMIT:{path.name}:{size}")
        digest = sha256_file(path)
        shard = path.stem.replace("santa-fe-buildings-3d-", "")
        destination = path.with_name(f"santa-fe-buildings-3d-{shard}.{digest[:16]}.pmtiles")
        path.replace(destination)
        finalized.append({"path": destination, "size": size, "sha256": digest})

    finalized.sort(key=lambda item: item["path"].name)
    asset_paths = [f"/data/santa-fe-3d/{item['path'].name}" for item in finalized]
    sizes = [item["size"] for item in finalized]
    hashes = [item["sha256"] for item in finalized]
    manifest = {
        **stats,
        "schema_version": 1,
        "city_id": CITY_ID,
        "layer": LAYER_NAME,
        "public_boundary_source": {
            "name": "OpenStreetMap Nominatim public Santa Fe place boundary, simplified city-scale urban envelope",
            "path": "/data/santa-fe-3d/public-urban-boundary.geojson",
            "license": "ODbL-1.0",
        },
        "source_dataset_releases": {
            "Overture Maps Buildings": OVERTURE_RELEASE,
            "Overture schema": "v1.18.0",
        },
        "source_licenses": {
            "Overture Maps Buildings": "ODbL-1.0 (contains OpenStreetMap-derived buildings)",
            "OpenStreetMap": "ODbL-1.0",
        },
        "source_attributions": ["© OpenStreetMap contributors", "© Overture Maps Foundation"],
        "build_tool_versions": {
            "overturemaps-py": OVERTURE_PY_VERSION,
            "tippecanoe_commit": TIPPECANOE_COMMIT,
            "go-pmtiles": PMTILES_CLI_VERSION,
            "python": sys.version.split()[0],
        },
        "build_command": "bash scripts/santa-fe-3d/materialize.sh",
        "asset_paths": asset_paths,
        "asset_sizes": sizes,
        "asset_sha256": hashes,
        "asset_under_24_mib_target": all(size <= ASSET_TARGET_BYTES for size in sizes),
        "asset_under_25_mib_hard_limit": all(size < ASSET_HARD_LIMIT_BYTES for size in sizes),
        "asset_shard_count": len(finalized),
        "created_from_commit": source_sha,
        "height_values_are_visual_massing_not_survey_measurements": True,
        "private_tracking_data_in_assets": False,
        "user_markers_in_dataset": False,
        "sessions_or_capabilities_in_dataset": False,
    }
    manifest_path = finalized[0]["path"].with_name("manifest.json")
    manifest_path.write_bytes(canonical_json(manifest))

    generated = Path(args.generated_ts)
    generated.parent.mkdir(parents=True, exist_ok=True)
    generated.write_text(
        "// Generated by scripts/santa-fe-3d/finalize_shards.py; commit with matching PMTiles assets.\n"
        f"export const SANTA_FE_3D_ASSET_PATHS = {json.dumps(asset_paths)} as const\n"
        "export const SANTA_FE_3D_SOURCE_LAYER = 'santa_fe_buildings_3d' as const\n"
        f"export const SANTA_FE_3D_ASSET_SHA256 = {json.dumps(hashes)} as const\n"
        f"export const SANTA_FE_3D_FEATURE_COUNT = {int(stats['final_features'])} as const\n"
        f"export const SANTA_FE_3D_BOUNDS = {json.dumps(stats['public_boundary_bounds'])} as const\n",
        encoding="utf-8",
    )
    print(json.dumps(manifest, indent=2, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
